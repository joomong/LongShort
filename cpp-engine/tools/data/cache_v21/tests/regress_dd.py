def run(cmd, what, cwd=None):
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True, cwd=cwd)
    if r.returncode != 0:
        raise SystemExit(f"{what} failed (rc {r.returncode}):\n{r.stdout[-2000:]}\n{r.stderr[-4000:]}")
    return r


class Probe:
    """Compile the XML-driven probe against <build>/libengine.a using the build's own compile/link lines."""

    def __init__(self, build_dir: Path, work: Path, rebuild: bool):
        self.build = build_dir.resolve()
        work.mkdir(parents=True, exist_ok=True)
        cache = self.build / "CMakeCache.txt"
        if not cache.exists():
            raise SystemExit(f"--build-dir {self.build} has no CMakeCache.txt")
        self.source = None
        for line in cache.read_text().splitlines():
            if line.startswith("CMAKE_HOME_DIRECTORY:INTERNAL="):
                self.source = Path(line.split("=", 1)[1])
        if rebuild:
            run(["cmake", "--build", str(self.build), "--target", "engine", "--parallel", "6"], "cmake --build")
        self.lib = self.build / "libengine.a"
        if not self.lib.exists():
            raise SystemExit(f"{self.lib} missing")
        newest = max(p.stat().st_mtime for p in (self.source / "src").rglob("*.h"))
        if newest > self.lib.stat().st_mtime + 1:
            raise SystemExit(f"headers under {self.source}/src are newer than {self.lib}; pass --rebuild-probe")
        cc = json.loads((self.build / "compile_commands.json").read_text())
        entry = next(e for e in cc if e["file"].endswith("tools/data_load_probe.cpp"))
        flags = shlex.split(entry["command"])
        stripped, i = [], 0
        while i < len(flags):
            if flags[i] in ("-o", "-c"):
                i += 2
                continue
            stripped.append(flags[i])
            i += 1
        src, obj, exe = work / "v2_probe.cpp", work / "v2_probe.o", work / "v2_probe"
        src.write_text(PROBE_SOURCE)
        run(stripped + ["-o", str(obj), "-c", str(src)], "compile probe")
        link = (self.build / "CMakeFiles" / "data_load_probe.dir" / "link.txt").read_text().split()
        linked, i = [], 0
        while i < len(link):
            if link[i].endswith("data_load_probe.cpp.o"):
                linked.append(str(obj))
            elif link[i] == "-o":
                linked += ["-o", str(exe)]
                i += 1
            else:
                linked.append(link[i])
            i += 1
        run(linked, "link probe", cwd=self.build)
        self.exe = exe
        self.lib_sha = sha256(self.lib)

    def run(self, config: Path, xml: str, mode: int, out_json: Path) -> dict:
        r = subprocess.run([str(self.exe), str(config), xml, str(mode), str(out_json)], capture_output=True, text=True)
        payload = json.loads(out_json.read_text()) if out_json.exists() else {}
        if r.returncode != 0:
            raise SystemExit(f"probe failed for {config} mode {mode}: {payload.get('error', r.stderr.strip())}")
        payload["stderr"] = r.stderr.strip()
        return payload


def sha256(path: Path) -> str:
    import hashlib
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


