def trading_days(root: Path) -> pd.DatetimeIndex:
    cal = pq.read_table(root / "calendar.parquet").to_pandas()
    return pd.DatetimeIndex(cal.loc[cal.isTradingDay, "date"].sort_values().values)


def peers_on(root: Path, ex: pd.Timestamp, n: int, exclude: set[int], seed: int) -> list[int]:
    mem = pq.read_table(root / "universe" / "membership.parquet").to_pandas()
    top = mem[(mem.universe == "Top500") & (mem.fromDate <= ex) & (mem.toDate >= ex)].tradingItemId.unique()
    top = np.array(sorted(int(t) for t in top if int(t) not in exclude))
    rng = np.random.default_rng(seed)
    return sorted(int(t) for t in rng.choice(top, min(n, top.size), replace=False))


def build_fixture(root: Path, case: dict, out: Path, peers: int, window: int, warmup: int) -> dict:
    ex = pd.Timestamp(case["ex"])
    days = trading_days(root)
    k = int(np.searchsorted(days, ex))
    if days[k] != ex:
        raise SystemExit(f"{ex.date()} is not a trading day in the calendar")
    start, end = days[k - window - warmup], days[min(k + window, len(days) - 1)]
    ids = sorted(set(peers_on(root, ex, peers, {case["parent"], case["child"]}, seed=int(ex.strftime("%Y%m%d")))) | {case["parent"], case["child"]})
    cv = CacheV21(root, ids=ids, start=start, end=end, threads=4)
    man = cv.export_wide(out, fields=("close",), basis="split_adj", returns=True, masks=(), universes=())
    close = pd.read_parquet(out / "BaseData" / "close.parquet")
    rets = pd.read_parquet(out / "Returns" / "returns_total.parquet")
    if not close.index.equals(rets.index) or list(close.columns) != list(rets.columns):
        raise SystemExit("close/returns wide panels disagree on axes")
    return {"ids": ids, "start": str(start.date()), "end": str(end.date()), "ex_bar": int(np.flatnonzero(close.index == ex)[0]),
            "dates": close.index, "close": close, "ret_v2": rets, "manifest": man, "ledger": out / "engine" / "ca_ledger_cache.parquet"}


def write_config(fx: dict, out: Path, warmup: int, child_in_universe: bool, case: dict) -> Path:
    """Strategy universe as a wide 0/1 file (engine `universe.path`): every panel symbol is a member; when the child is
    OUT of the strategy it is a member on the warmup bars only (keeps it in the price panel — the engine drops symbols
    that are never members — while its signal is masked and its target is 0 on every trading bar, P8 liquidation)."""
    symbols = [str(c) for c in fx["close"].columns]
    uni = pd.DataFrame(1.0, index=fx["dates"], columns=symbols, dtype=np.float32)
    if not child_in_universe:
        uni.loc[uni.index[warmup]:, str(case["child"])] = 0.0
    tag = "child_in" if child_in_universe else "child_out"
    (out / "Universe").mkdir(exist_ok=True)
    upath = out / "Universe" / f"strategy_{tag}.parquet"
    uni.index.name = None
    uni.to_parquet(upath)
    lines = [
        "datasets:",
        "  - name: prices",
        f"    path: {out}",
        "    format: wide",
        "    time_col: __index_level_0__",
        "    fields: {close: BaseData/close.parquet, ret_v2: Returns/returns_total.parquet}",
        "universe:",
        f"  path: {upath}",
        "  time_col: __index_level_0__",
        "backtest:",
        f"  start_date: '{fx['dates'][warmup].strftime('%Y-%m-%d')}'",
        f"  end_date: '{fx['dates'][-1].strftime('%Y-%m-%d')}'",
        f"  transaction_fee: {FEE_BPS}",
        f"  warmup_bars: {warmup}",
        "  missing_close_policy: carry",
        f"  corporate_actions: {{path: '{fx['ledger']}', stale_check: true}}",
    ]
    cfg = out / f"config_{tag}.yaml"
    cfg.write_text("\n".join(lines) + "\n")
    return cfg


