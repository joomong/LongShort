def bar_table(res: dict, fx: dict, sym: str, lo: int, hi: int, mode: int) -> pd.DataFrame:
    """Per-bar path of one symbol. D1: the signal of bar t becomes the target executed at bar t+1's close
    (desired[t] is what the engine executed at bar t)."""
    n = res["symbols"].index(sym)
    rows = []
    for t in range(max(lo, 0), min(hi, res["T"] - 1) + 1):
        b = res["bars"][t]
        rows.append({
            "bar": t, "date": pd.Timestamp(res["timestamps"][t], unit="ms").strftime("%Y-%m-%d"),
            "close_adj": res["close"][t][n],
            "ret_price": (res["close"][t][n] / res["close"][t - 1][n] - 1.0) if t > 0 and res["close"][t - 1][n] and res["close"][t][n] else np.nan,
            "ret_v2": float(fx["ret_v2"].iloc[t][sym]) if sym in fx["ret_v2"].columns else np.nan,
            "signal": res["signal"][t][n],
            "target_w": b["desired"][n],
            "trade_w": b["trades"][n],
            "weight_after": b["weights"][n],
            "mark_before": b["marksBefore"][n],
            "gross_bar": b["gross"], "turnover_bar": b["turnover"], "fee_bar": b["fee"],
            "divPnl": b["corporateActions"]["dividendPnl"], "distPnl": b["corporateActions"]["distributionPnl"],
            "distCount": b["corporateActions"]["distributionCount"], "childCreated": b["corporateActions"]["childPositionsCreated"],
        })
    return pd.DataFrame(rows)


def pct_below(row: list, x: float) -> float:
    vals = [v for v in row if v is not None and np.isfinite(v)]
    return float(np.mean([v <= x for v in vals])) if vals else float("nan")


def fmt_table(df: pd.DataFrame) -> str:
    cols = ["bar", "date", "close_adj", "ret_price", "ret_v2", "signal", "target_w", "trade_w", "weight_after", "distPnl", "childCreated", "turnover_bar", "fee_bar"]
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, (float, np.floating)):
                cells.append("nan" if not np.isfinite(v) else (f"{v:+.4%}" if c in ("ret_price", "ret_v2") else f"{v:.6f}" if c != "close_adj" else f"{v:.4f}"))
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def distortion_window(cres: dict, cdir: Path, ex_bar: int, md: list[str], pre: int = 15, post: int = 6):
    """Signal path of the parent under input (i) and (ii) around the ex-date (child OUT, D1): raw signal, cross-sectional
    percentile of the signal, executed target next bar; verdict numbers: how many bars the price-input signal sits at
    an extreme (pct >= 0.98 or <= 0.02) after the ex-date, and whether the v2-input ex-date signal stays inside the
    parent's own pre-event range (min/max of the `pre` bars before the ex-date)."""
    dumps = {k: json.loads((cdir / f"engine_{k}_childout_D1.json").read_text()) for k in ALPHAS}
    psym = str(cres["parent"])
    n = dumps["price"]["symbols"].index(psym)
    rows = []
    for t in range(ex_bar - 2, ex_bar + post + 1):
        r = {"bar": t, "date": pd.Timestamp(dumps["price"]["timestamps"][t], unit="ms").strftime("%Y-%m-%d")}
        for k, d in dumps.items():
            sig = d["signal"][t][n]
            r[f"sig_{k}"] = sig
            r[f"pct_{k}"] = pct_below(d["signal"][t], sig) if sig is not None and np.isfinite(sig) else np.nan
            r[f"target_next_{k}"] = d["bars"][t + 1]["desired"][n] if t + 1 < d["T"] else np.nan
        rows.append(r)
    tab = pd.DataFrame(rows)
    verdict = {}
    for k, d in dumps.items():
        pre_sig = [d["signal"][t][n] for t in range(ex_bar - pre, ex_bar) if d["signal"][t][n] is not None and np.isfinite(d["signal"][t][n])]
        post_pct = [pct_below(d["signal"][t], d["signal"][t][n]) for t in range(ex_bar, ex_bar + post + 1)]
        sig_ex = d["signal"][ex_bar][n]
        verdict[k] = {"pre_min": float(np.min(pre_sig)), "pre_max": float(np.max(pre_sig)), "signal_ex": sig_ex,
                      "ex_inside_pre_range": bool(np.min(pre_sig) <= sig_ex <= np.max(pre_sig)),
                      "bars_at_extreme_after_ex": int(sum(1 for q in post_pct if np.isfinite(q) and (q >= 0.98 or q <= 0.02))),
                      "pct_ex": post_pct[0], "abs_target_next_max_after_ex": float(np.nanmax([abs(d["bars"][t + 1]["desired"][n]) for t in range(ex_bar, ex_bar + post)])),
                      "max_abs_weight_in_book": float(np.nanmax([abs(x) for x in d["bars"][ex_bar + 1]["desired"] if x is not None]))}
    cres["distortion"] = {"table": tab.to_dict("records"), "verdict": verdict}
    md.append("\n### signal distortion window (child OUT of universe, D1): parent signal / cross-sectional pct / target executed next bar\n")
    md.append("| bar | date | sig (i) price | pct (i) | target next (i) | sig (ii) v2 | pct (ii) | target next (ii) |")
    md.append("|---|---|---|---|---|---|---|---|")
    for r in rows:
        f = lambda x, p="{:+.4f}": ("nan" if x is None or not np.isfinite(x) else p.format(x))
        md.append(f"| {r['bar']} | {r['date']} | {f(r['sig_price'])} | {f(r['pct_price'], '{:.2f}')} | {f(r['target_next_price'], '{:+.5f}')} | {f(r['sig_v2'])} | {f(r['pct_v2'], '{:.2f}')} | {f(r['target_next_v2'], '{:+.5f}')} |")
    md.append("")
    md.append("| input | pre-event signal range (15 bars) | signal at ex | inside pre range | pct at ex | bars at cross-sectional extreme (pct >= 0.98 or <= 0.02) in ex..ex+6 | max abs target next after ex | max abs weight in book |")
    md.append("|---|---|---|---|---|---|---|---|")
    for k, v in verdict.items():
        md.append(f"| {k} | [{v['pre_min']:+.3f}, {v['pre_max']:+.3f}] | {v['signal_ex']:+.4f} | {'yes' if v['ex_inside_pre_range'] else 'NO'} | {v['pct_ex']:.2f} | {v['bars_at_extreme_after_ex']} | {v['abs_target_next_max_after_ex']:.5f} | {v['max_abs_weight_in_book']:.5f} |")


def live_replay(root: Path, out_lines: list[str], results: dict):
    """DD 2025-10-30..11-10 in SHARES for a ~20k-share long holding (raw closes from base_data; live orders = lead's
    observation). Three mechanical paths, no engine needed (the engine works in fixed-book weights):
      H1  live rule 'share target = value / prev close' with the value target unchanged (= fixed-book constant weight,
          which is what the engine's unchanged parent weight means after a spin-off: the implicit top-up is not turnover);
      H2  constant shares (position carried, nothing re-targeted) -> orders 0;
      IMPLIED  the value target that the live orders imply (cum shares x prev close) relative to the pre-event one.
    The engine (P7/P8) additionally books the child: 0.5 x shares of Q received at the ex-date close and sold at the next
    executable close (D1) -> child share path. Signal input (price vs v2) only changes the target weight w_t; it does not
    change this mechanics."""
    parent, child = CASES["dd"]["parent"], CASES["dd"]["child"]
    t = pq.read_table(root / "base_data.parquet", columns=["date", "tradingItemId", "close"],
                      filters=[("tradingItemId", "in", [parent, child]), ("date", ">=", pd.Timestamp("2025-10-24")), ("date", "<=", pd.Timestamp("2025-11-10"))]).to_pandas()
    raw = t.pivot(index="date", columns="tradingItemId", values="close").astype(float)
    v2 = pq.read_table(root / "derived" / "returns_total.parquet", columns=["date", "tradingItemId", "ret", "retFlag"],
                       filters=[("tradingItemId", "==", parent), ("date", ">=", pd.Timestamp("2025-10-24")), ("date", "<=", pd.Timestamp("2025-11-10"))]).to_pandas().set_index("date")
    rc1_path = root / "derived" / "returns_total_rc1.parquet"
    rc1 = None
    if rc1_path.exists():
        rc1 = pq.read_table(rc1_path, columns=["date", "tradingItemId", "ret"],
                            filters=[("tradingItemId", "==", parent), ("date", ">=", pd.Timestamp("2025-10-24")), ("date", "<=", pd.Timestamp("2025-11-10"))]).to_pandas().set_index("date")
    dd = raw[parent]
    q = raw[child] if child in raw.columns else pd.Series(dtype=float)
    ratio = 0.5
    rows = []
    shares0 = LIVE_DD_POSITION
    V = shares0 * float(dd.loc["2025-10-31"])          # value target anchored on the 10-31 close (= 20k shares)
    h1_prev = shares0
    live_shares = shares0
    V_prev_live = None
    child_held = 0.0
    for d in pd.DatetimeIndex(sorted(dd.index)):
        ds = d.strftime("%Y-%m-%d")
        if ds < "2025-10-30":
            continue
        i = dd.index.get_loc(d)
        c_prev = float(dd.iloc[i - 1])
        r_price_day = float(dd.iloc[i]) / c_prev - 1
        r_v2_day = float(v2.ret.get(d, np.nan))
        r_rc1_day = float(rc1.ret.get(d, np.nan)) if rc1 is not None else np.nan
        h1_shares = V / c_prev
        h1_order = h1_shares - h1_prev
        h1_prev = h1_shares
        live_order = LIVE_DD_TRADES.get(ds, np.nan)
        if np.isfinite(live_order):
            live_shares += live_order
        V_live = live_shares * c_prev if np.isfinite(live_order) else np.nan   # value the live share target implies
        V_ratio = (V_live / V_prev_live) if (np.isfinite(V_live) and V_prev_live) else np.nan
        if np.isfinite(V_live):
            V_prev_live = V_live
        # engine P7/P8 child path for the H1 holding: received at ex close, sold at the next close (D1)
        child_recv = child_sold = 0.0
        if ds == CASES["dd"]["ex"]:
            child_recv = ratio * shares0                       # 0.5 x shares held into the ex-date
            child_held = child_recv
        elif child_held:
            child_sold = -child_held
            child_held = 0.0
        rows.append({"date": ds, "DD_close": float(dd.iloc[i]), "Q_close": float(q.get(d, np.nan)), "DD_prev_close": c_prev,
                     "r_price_day": r_price_day, "r_v2_day": r_v2_day, "r_rc1_day": r_rc1_day,
                     "live_order": live_order, "live_shares_after": live_shares if np.isfinite(live_order) else np.nan,
                     "live_implied_value_target": V_live, "live_implied_value_ratio": V_ratio,
                     "H1_target_shares": h1_shares, "H1_order": h1_order, "H2_const_shares_order": 0.0,
                     "engine_child_Q_received": child_recv, "engine_child_Q_sold_next": child_sold,
                     "engine_child_value": child_recv * float(q.get(d, np.nan)) if child_recv else (abs(child_sold) * float(q.get(d, np.nan)) if child_sold else 0.0)})
    df = pd.DataFrame(rows)
    ex = df[df.date == CASES["dd"]["ex"]].iloc[0]
    nx = df[df.date > CASES["dd"]["ex"]].iloc[0]
    rep = {"table": df.to_dict("records"),
           "price_ratio_ex": float(ex.DD_close / ex.DD_prev_close),
           "H1_order_next_day": float(nx.H1_order), "live_order_next_day": float(nx.live_order),
           "live_implied_value_ratio_next_day": float(nx.live_implied_value_ratio),
           "child_Q_received_shares": float(ex.engine_child_Q_received), "child_Q_value_at_ex": float(ex.engine_child_Q_received * ex.Q_close),
           "child_Q_sold_next_shares": float(nx.engine_child_Q_sold_next), "child_Q_sale_value": float(-nx.engine_child_Q_sold_next * nx.Q_close),
           "DD_cash_style_ret_ex": float(ex.r_v2_day), "DD_price_ret_ex": float(ex.r_price_day)}
    results["live_replay"] = rep
    out_lines.append("\n### Live DD order pattern replay in shares (raw closes from base_data; live orders = lead's observation, ~20k-share holding)\n")
    out_lines.append("| date | DD close | Q close | DD prev close | r_price | r_v2 (cash-style) | r_rc1 (vendor) | live order | live shares after | live implied value target | ratio vs prev | H1 target shares (V/prev close, V fixed) | H1 order | engine child Q received (P7) | engine child Q sold next close (P8) |")
    out_lines.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        f = lambda x, p="{:+.2%}": ("nan" if x is None or not np.isfinite(x) else p.format(x))
        out_lines.append(f"| {r['date']} | {r['DD_close']:.2f} | {f(r['Q_close'], '{:.2f}')} | {r['DD_prev_close']:.2f} | {f(r['r_price_day'])} | {f(r['r_v2_day'])} | {f(r['r_rc1_day'])} | {f(r['live_order'], '{:+.0f}')} | {f(r['live_shares_after'], '{:,.0f}')} | {f(r['live_implied_value_target'], '{:,.0f}')} | {f(r['live_implied_value_ratio'], '{:.4f}')} | {r['H1_target_shares']:,.0f} | {r['H1_order']:+,.0f} | {r['engine_child_Q_received']:+,.0f} | {r['engine_child_Q_sold_next']:+,.0f} |")
    out_lines.append("")
    out_lines.append(f"- price ratio at ex {rep['price_ratio_ex']:.4f}; H1 (value target unchanged) order on {nx.date}: {rep['H1_order_next_day']:+,.0f} shares vs live {rep['live_order_next_day']:+,.0f}; "
                     f"live implied value target ratio {rep['live_implied_value_ratio_next_day']:.4f} (= price ratio x {rep['live_implied_value_ratio_next_day'] / rep['price_ratio_ex']:.4f}).")
    out_lines.append(f"- engine P7/P8 for the same holding: {rep['child_Q_received_shares']:,.0f} Q received at {ex.Q_close:.2f} (value {rep['child_Q_value_at_ex']:,.0f}) on {ex.date}, sold at the next close {nx.Q_close:.2f} (value {rep['child_Q_sale_value']:,.0f}) with fee {FEE_BPS} bp; "
                     f"DD ex-date return booked {rep['DD_cash_style_ret_ex']:+.4%} (cash-style, = raw price {rep['DD_price_ret_ex']:+.2%} + Q value), not the vendor {ex.r_rc1_day:+.4%}.")
    return df


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache-root", required=True, type=Path)
    ap.add_argument("--build-dir", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--cases", default="dd,wdc,hon")
    ap.add_argument("--peers", type=int, default=60)
    ap.add_argument("--window", type=int, default=25)
    ap.add_argument("--warmup", type=int, default=8)
    ap.add_argument("--rebuild-probe", action="store_true")
    args = ap.parse_args(argv)
    t0 = time.time()
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    probe = Probe(args.build_dir, out / "probe", args.rebuild_probe)
    root = args.cache_root.resolve()
    ledger_raw = root / "events" / "ca_ledger.parquet"
    results = {"build_dir": str(probe.build), "libengine_sha256": probe.lib_sha, "cache_root": str(root),
               "ledger_raw": str(ledger_raw.resolve()), "ledger_raw_sha256": sha256(ledger_raw),
               "returns_v2": str((root / "derived" / "returns_total.parquet").resolve()),
               "returns_v2_sha256": sha256(root / "derived" / "returns_total.parquet"), "cases": {}}
    md = [f"# V2 regress_dd — engine signal regression around spin-offs ({time.strftime('%Y-%m-%d %H:%M')})\n",
          f"build `{probe.build}` (libengine.a sha256 {probe.lib_sha[:12]}), raw ledger `{ledger_raw.resolve()}` sha256 {results['ledger_raw_sha256'][:12]}, "
          f"returns v2 `{results['returns_v2']}` sha256 {results['returns_v2_sha256'][:12]}, fee {FEE_BPS} bp, D1 unless noted.\n",
          "alpha (i) price input: `" + ALPHAS["price"] + "`; alpha (ii) v2 input: `" + ALPHAS["v2"] + "` (tsmean over 5 daily returns, cross-sectional pct rank, z-scored; targets = signal / Σ|signal|).\n"]
    for key in args.cases.split(","):
        case = CASES[key]
        cdir = out / key
        fx = build_fixture(root, case, cdir, args.peers, args.window, args.warmup)
        ex_bar = fx["ex_bar"]
        exp = dict(fx["manifest"]["ca_ledger"])
        exp["rows"] = fx["manifest"]["files"]["engine/ca_ledger_cache.parquet"]["rows"]
        exp["sha256"] = fx["manifest"]["files"]["engine/ca_ledger_cache.parquet"]["sha256"]
        cres = {"parent": case["parent"], "child": case["child"], "ex": case["ex"], "ids": fx["ids"], "start": fx["start"], "end": fx["end"], "ex_bar": ex_bar,
                "export_manifest": {k: v for k, v in exp.items() if k != "events_excluded_rows"}, "runs": {}}
        L = pq.read_table(fx["ledger"]).to_pandas()
        lrow = L[(L.tradingItemId == str(case["parent"])) & (L.exDate == pd.Timestamp(case["ex"]))]
        cres["ledger_rows_on_ex"] = json.loads(lrow.to_json(orient="records", date_format="iso"))
        md.append(f"\n## {key.upper()} — {case['label']}\n")
        md.append(f"panel {len(fx['ids'])} ids ({args.peers} Top500 peers on {case['ex']} + parent + child), {fx['start']}..{fx['end']}, ex bar {ex_bar}, warmup {args.warmup}; "
                  f"loader export rows {exp['rows']} (stock legs {exp['rows_by_leg'].get('stock', 0)}, child close observed {exp['child_close_observed']}).\n")
        md.append("ledger export rows on the ex-date:\n")
        md.append("| tradingItemId | eventType | legType | cashPerShareCache | child | childRatioCache | childRatioRaw | childCloseAtExCache | parentCloseBeforeCache | parentCloseAtExCache | status | childValueSource |")
        md.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for _, r in lrow.iterrows():
            md.append(f"| {r.tradingItemId} | {r.eventType} | {r.legType} | {r.cashPerShareCache} | {r.childTradingItemId} | {r.childRatioCache} | {r.childRatioRaw} | {r.childCloseAtExCache} | {r.parentCloseBeforeCache} | {r.parentCloseAtExCache} | {r.status} | {r.childValueSource} |")
        for child_in in (False, True):
            cfg = write_config(fx, cdir, args.warmup, child_in, case)
            for alpha_key, xml in ALPHAS.items():
                for mode in (1, 0):
                    tag = f"{alpha_key}_{'childin' if child_in else 'childout'}_D{mode}"
                    res = probe.run(cfg, xml, mode, cdir / f"engine_{tag}.json")
                    psym, csym = str(case["parent"]), str(case["child"])
                    pt = bar_table(res, fx, psym, ex_bar - 6, ex_bar + 8, mode)
                    ct = bar_table(res, fx, csym, ex_bar - 1, ex_bar + 8, mode)
                    dists = [d for d in res["distributions"] if res["symbols"][d["parent"]] == psym]
                    cres["runs"][tag] = {"xml": res["xml"], "parent": pt.to_dict("records"), "child": ct.to_dict("records"), "distributions": dists,
                                         "ledgerReport": res["ledgerReport"], "sum_gross": float(np.nansum([b["gross"] for b in res["bars"]])),
                                         "sum_turnover": float(np.nansum([b["turnover"] for b in res["bars"]]))}
                    if mode == 1:
                        md.append(f"\n### alpha ({'i' if alpha_key == 'price' else 'ii'}) {alpha_key} input, child {'IN' if child_in else 'OUT of'} strategy universe, D1\n")
                        md.append(f"parent {psym}:\n\n" + fmt_table(pt) + "\n")
                        md.append(f"child {csym}:\n\n" + fmt_table(ct) + "\n")
                        md.append("distribution records: " + json.dumps(dists) + "\n")
        # summary numbers for the verdict
        summ = {}
        for alpha_key in ALPHAS:
            r1 = cres["runs"][f"{alpha_key}_childout_D1"]
            pt = pd.DataFrame(r1["parent"]).set_index("bar")
            sig_ex, sig_pre = pt.loc[ex_bar, "signal"], pt.loc[ex_bar - 1, "signal"]
            tgt_next = pt.loc[ex_bar + 1, "target_w"]
            tgt_pre = pt.loc[ex_bar, "target_w"]
            w_after_ex = pt.loc[ex_bar, "weight_after"]
            trade_next = pt.loc[ex_bar + 1, "trade_w"]
            ct = pd.DataFrame(r1["child"]).set_index("bar")
            summ[alpha_key] = {"parent_signal_ex": sig_ex, "parent_signal_before": sig_pre, "parent_target_executed_next_bar": tgt_next,
                               "parent_target_executed_ex_bar": tgt_pre, "parent_weight_after_ex": w_after_ex, "parent_trade_next_bar": trade_next,
                               "parent_signal_rank_ex": pct_below(json.loads((cdir / f"engine_{alpha_key}_childout_D1.json").read_text())["signal"][ex_bar], sig_ex),
                               "child_weight_created": ct.loc[ex_bar, "weight_after"], "child_trade_next_bar": ct.loc[ex_bar + 1, "trade_w"],
                               "child_weight_after_next": ct.loc[ex_bar + 1, "weight_after"], "child_fee_next_bar": FEE_BPS / 1e4 * abs(ct.loc[ex_bar + 1, "trade_w"]),
                               "ex_bar_distPnl": pt.loc[ex_bar, "distPnl"], "ex_bar_ret_price": pt.loc[ex_bar, "ret_price"], "ex_bar_ret_v2": pt.loc[ex_bar, "ret_v2"]}
        cres["summary"] = summ
        md.append("\n### summary (child OUT of universe, D1)\n")
        md.append("| input | parent signal t−1 | parent signal ex | pct of names below ex signal | target executed at ex close | target executed next close | trade next close | weight after ex | child weight created | child trade next | child fee next | ex-bar distPnl | ex-bar price ret | ex-bar v2 ret |")
        md.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        for k, s in summ.items():
            md.append(f"| {k} | {s['parent_signal_before']:.4f} | {s['parent_signal_ex']:.4f} | {s['parent_signal_rank_ex']:.2f} | {s['parent_target_executed_ex_bar']:.5f} | {s['parent_target_executed_next_bar']:.5f} | {s['parent_trade_next_bar']:+.5f} | {s['parent_weight_after_ex']:.5f} | {s['child_weight_created']:.5f} | {s['child_trade_next_bar']:+.5f} | {s['child_fee_next_bar']:.2e} | {s['ex_bar_distPnl']:+.6f} | {s['ex_bar_ret_price']:+.4%} | {s['ex_bar_ret_v2']:+.4%} |")
        distortion_window(cres, cdir, ex_bar, md)
        results["cases"][key] = cres
    if "dd" in args.cases.split(","):
        live_replay(root, md, results)
    results["seconds"] = round(time.time() - t0, 1)
    (out / "regress_dd.json").write_text(json.dumps(results, indent=1, default=str))
    (out / "regress_dd.md").write_text("\n".join(md) + "\n")
    print(f"wrote {out / 'regress_dd.md'} ({results['seconds']} s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
