def run_comparison(paths: list, output: Path, expected_file: Path = None,
                   baseline_runs: list = None) -> int:
    """First path is the frozen baseline directory, the rest are new run directories."""
    baseline = Path(paths[0])
    expected = None
    if expected_file:
        text = Path(expected_file).read_text()
        expected = {line.split(",")[0].strip() for line in text.splitlines()[1:] if line.strip()}
    after_frames = []
    for directory in paths[1:]:
        path = Path(directory) / "settlement_log.csv"
        if not path.exists():
            raise FileNotFoundError(f"no settlement_log.csv in {directory}")
        after_frames.append(pd.read_csv(path))
    after = pd.concat(after_frames, ignore_index=True)
    before_frames = []
    for universe in sorted(after.universe.astype(str).unique()):
        candidate = baseline / f"settlement_log_{universe}.csv"
        if not candidate.exists():
            candidate = baseline / universe / "settlement_log.csv"
        if not candidate.exists():
            raise FileNotFoundError(f"no baseline log for {universe} under {baseline}")
        before_frames.append(pd.read_csv(candidate))
    before = pd.concat(before_frames, ignore_index=True)
    result = compare_settlement_logs(before, after, expected)
    output.mkdir(parents=True, exist_ok=True)
    result["changed"].to_csv(output / "changed_settlements.csv", index=False)
    result["totals"].to_csv(output / "settlement_totals.csv", index=False)
    text = render_comparison(result)
    if baseline_runs:
        table = run_pnl_table(baseline_runs, paths[1:])
        table.to_csv(output / "run_pnl.csv", index=False)
        text += "\n".join(render_run_pnl(table)) + "\n"
        total = table.pnl_diff.abs().max()
        print(f"whole-run PnL: max |diff| {total:.6f} across {len(table)} runs")
    (output / "comparison.md").write_text(text)
    print(f"comparison: {result['status']}, {len(result['changed'])} changed rows, "
          f"{len(result['securities'])} securities, "
          f"{len(result['unexpected'])} unexpected -> {output / 'comparison.md'}")
    return 0 if result["status"] == "PASS" else 1


def merge_worklists(destination: Path, sources: list) -> Path:
    """Combine per-universe worklists into one row per security.

    Exposure is kept per universe as its own column plus an overall maximum, and
    the ordering follows the widest book first: Top500, then Top1000, then ALL.
    """
    frames = []
    for path in sources:
        path = Path(path)
        if not path.exists():
            raise FileNotFoundError(f"worklist not found: {path}")
        frames.append(pd.read_csv(path))
    combined = pd.concat(frames, ignore_index=True)
    combined["tradingItemId"] = combined.tradingItemId.astype(str)
    grouped = combined.groupby("tradingItemId", as_index=False).agg(
        ticker=("ticker", "first"), endDate=("endDate", "first"),
        actionCode=("actionCode", "first"), cacheUnitStatus=("cacheUnitStatus", "first"),
        hasStockLeg=("hasStockLeg", "first"), alphas=("alphas", "max"),
        universe=("universe", lambda values: ",".join(sorted(set(map(str, values))))),
        actionText=("actionText", "first"))
    names = [name for name in combined.universe.astype(str).unique()]
    order = [name for name in ("Top500", "Top1000", "ALL") if name in names]
    order += [name for name in sorted(names) if name not in order]
    for name in order:
        subset = combined[combined.universe.astype(str) == name]
        column = f"max_abs_exposure_{name}"
        grouped[column] = grouped.tradingItemId.map(
            subset.groupby("tradingItemId").max_abs_exposure.max())
    exposure_columns = [f"max_abs_exposure_{name}" for name in order]
    grouped["max_abs_exposure"] = grouped[exposure_columns].max(axis=1)
    grouped = grouped.sort_values(exposure_columns, ascending=False, na_position="last")
    columns = (["tradingItemId", "ticker", "endDate", "actionCode", "cacheUnitStatus",
                "hasStockLeg"] + exposure_columns
               + ["max_abs_exposure", "alphas", "universe", "actionText"])
    destination.parent.mkdir(parents=True, exist_ok=True)
    grouped[columns].to_csv(destination, index=False)
    return destination



def validate_run(entry: dict, guard_required: bool, price_checks) -> dict:
    """Turn a numerically wrong or empty answer into a failure (review R3).

    A 200 that carries no bars, breaks the fee identity, or comes from a server
    that never ran the events price guard is not a successful run.
    """
    if entry.get("status") != "OK":
        return entry
    problems = []
    if not entry.get("bars"):
        problems.append("the response carries no trading bars")
    fee_error = entry.get("fee_identity_max_error")
    if fee_error is None:
        problems.append("no fee identity could be computed")
    elif fee_error > IDENTITY_TOLERANCE:
        problems.append(f"fee identity residual {fee_error:.3e} > {IDENTITY_TOLERANCE:g}")
    if guard_required and not price_checks:
        problems.append(f"config declares guard columns but eventsPriceChecks={price_checks}")
    absent = entry.get("missing_data_absent_keys")
    if absent:
        problems.append("missingData is missing " + ", ".join(absent))
    if problems:
        entry = {**entry, "status": "FAIL", "error": "; ".join(problems)}
    return entry


def validate_sensitivity(runs: list, rows: list) -> list:
    """The default-return sensitivity may move nothing but the settlement P&L."""
    by_alpha = {}
    for row in rows:
        if abs(row["residual"]) > IDENTITY_TOLERANCE:
            by_alpha[row["alpha"]] = f"R sensitivity residual {row['residual']:.3e}"
        elif not (row["turnover_matches"] and row["fee_matches"]):
            by_alpha[row["alpha"]] = "turnover or fee moved with defaultDelistingReturn"
    if not by_alpha:
        return runs
    return [{**run, "status": "FAIL",
             "error": "; ".join(filter(None, [run.get("error"), by_alpha[run["alpha"]]]))}
            if run["alpha"] in by_alpha and run["status"] == "OK" else run
            for run in runs]


def sensitivity_identity(runs: list) -> list:
    """Changing only defaultDelistingReturn may move nothing but the settlement P&L."""
    rows = []
    by_alpha = {}
    for run in runs:
        if run["status"] == "OK":
            by_alpha.setdefault(run["alpha"], {})[run["defaultDelistingReturn"]] = run
    for alpha, pair in by_alpha.items():
        if 0.0 not in pair or -1.0 not in pair:
            continue
        zero, minus = pair[0.0], pair[-1.0]
        settlement = ((minus.get("missing_data") or {}).get("delistingPnl", 0.0)
                      - (zero.get("missing_data") or {}).get("delistingPnl", 0.0))
        difference = minus["pnl"] - zero["pnl"]
        rows.append({"alpha": alpha, "pnl_r0": zero["pnl"], "pnl_r1": minus["pnl"],
                     "pnl_difference": difference, "settlement_difference": settlement,
                     "residual": difference - settlement,
                     "turnover_matches": abs(minus["turnover_total"] - zero["turnover_total"]) < 1e-9,
                     "fee_matches": abs(minus["fee_total"] - zero["fee_total"]) < 1e-12})
    return rows


