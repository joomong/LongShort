def universe_config(source: Path, universe: str, destination: Path) -> Path:
    """Copy the example config with universe.path swapped for another membership file.

    Relative dataset/catalog/universe/events paths are resolved against the
    original config directory first, so the copy can live anywhere.
    """
    universe_path = (Path(universe) if "/" in universe
                     else UNIVERSE_DIRECTORY / f"{universe}.parquet")
    if not universe_path.exists():
        raise FileNotFoundError(f"universe file not found: {universe_path}")
    config = yaml.safe_load(source.read_text())
    base = source.parent

    def absolute(value):
        return str((base / value).resolve()) if not Path(value).is_absolute() else value

    for dataset in config.get("datasets") or []:
        for key in ("path", "catalog"):
            if dataset.get(key):
                dataset[key] = absolute(dataset[key])
    for section, key in RELATIVE_CONFIG_PATHS:
        block = config.get(section)
        if isinstance(block, dict) and block.get(key):
            block[key] = absolute(block[key])
    if not isinstance(config.get("universe"), dict):
        config["universe"] = {}
    config["universe"]["path"] = str(universe_path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("# Generated by run_top500_missing_close.py --universe-path\n"
                           + yaml.safe_dump(config, sort_keys=False, allow_unicode=True))
    return destination


def summarize(response: dict, bars_per_year: int, fee_rate: float) -> dict:
    """Whole-period statistics recomputed from the returned timeseries."""
    timeseries = response.get("timeseries") or {}
    if not timeseries and response.get("batches"):
        timeseries = response["batches"][0].get("timeseries") or {}
    cum = np.asarray(timeseries.get("cumPnl", []), dtype=np.float64)
    if cum.size == 0:
        return {"bars": 0}
    ret = np.diff(np.concatenate([[0.0], cum]))
    turnover = np.asarray(timeseries.get("turnover", []), dtype=np.float64) / 100.0
    drawdown = np.asarray(timeseries.get("drawdown", []), dtype=np.float64)
    cum_gross = np.asarray(timeseries.get("cumPnlGross", []), dtype=np.float64)
    deviation = float(ret.std(ddof=1)) if ret.size > 1 else 0.0
    fee_total = float(turnover.sum()) * fee_rate
    summary = {
        "bars": int(cum.size),
        "first_bar": timeseries["timestamps"][0],
        "last_bar": timeseries["timestamps"][-1],
        "pnl": float(cum[-1]),
        "gross_pnl": float(cum_gross[-1]) if cum_gross.size else None,
        "sharpe_full": (float(ret.mean() / deviation * np.sqrt(bars_per_year))
                        if deviation > 0 else None),
        "max_drawdown": float(drawdown.min()) if drawdown.size else None,
        "turnover_total": float(turnover.sum()),
        "turnover_mean": float(turnover.mean()),
        "fee_total": fee_total,
        "position_count_mean": float(np.mean(timeseries.get("nonzeroCount", [0]))),
    }
    # Identity check: gross minus net must be exactly the accumulated fee.
    if cum_gross.size == cum.size:
        summary["fee_identity_max_error"] = float(
            np.max(np.abs((cum_gross - cum) - np.cumsum(turnover) * fee_rate)))
    # main.cpp keeps the IS/OS summary inside each batch entry, not at the top level.
    batches = response.get("batches") or [{}]
    summaries = response.get("summary") or (batches[0].get("summary") or {})
    for period in ("is", "os"):
        block = summaries.get(period) or {}
        # json_serializer.cpp reports these as percentage points, except sharpe.
        for key in ("sharpe", "pnl", "mdd", "return", "turnover", "minBet"):
            if key in block:
                summary[f"{period}_{key}"] = block[key]
    missing = response.get("missingData") or (batches[0].get("missingData") if batches else None)
    if isinstance(missing, dict):
        summary["missing_data"] = {key: missing[key] for key in MISSING_DATA_KEYS if key in missing}
        summary["missing_data_absent_keys"] = [key for key in MISSING_DATA_KEYS if key not in missing]
    return summary


def run_one(running, name: str, xml: str, default_return: float, options: dict,
            timeout: float) -> dict:
    payload = {"xml": xml, "simStart": options["sim_start"], "isStart": options["is_start"],
               "osStart": options["os_start"], "mode": options["mode"],
               "missingClose": options["missing_close"],
               "defaultDelistingReturn": default_return,
               "collectSignals": False, "settlementLog": options.get("settlement_log", True)}
    if options["stale_bars"] is not None:
        payload["staleQuoteSettleBars"] = options["stale_bars"]
    entry = {"alpha": name, "xml": xml, "defaultDelistingReturn": default_return,
             "mode": options["mode"], "missingClose": options["missing_close"]}
    if not running.alive():
        entry.update(status="ERROR", error="server exited before this run")
        return entry
    started = time.monotonic()
    try:
        response = request(running.base, "/api/simulate", payload, timeout=timeout)
    except HTTPError as error:
        body = error.read().decode(errors="replace")
        try:
            message = json.loads(body).get("error", body)
        except json.JSONDecodeError:
            message = body
        entry.update(status="FAIL", http_status=error.code,
                     error=message.strip().splitlines()[0] if message.strip() else body[:200],
                     seconds=round(time.monotonic() - started, 3))
    except (URLError, TimeoutError, ConnectionError, OSError) as error:
        entry.update(status="ERROR", error=f"{type(error).__name__}: {error}",
                     seconds=round(time.monotonic() - started, 3))
    else:
        entry.update(status="OK", seconds=round(time.monotonic() - started, 3))
        entry.update(summarize(response, options["bars_per_year"], options["fee_rate"]))
        if options.get("timeseries_dir"):
            # Opt-in: keep the per-bar series (cumPnl, turnover, ...) the summary was computed
            # from, one JSON per run, so downstream comparisons do not have to re-run the engine.
            timeseries = (response.get("timeseries")
                          or (response.get("batches") or [{}])[0].get("timeseries") or {})
            directory = Path(options["timeseries_dir"])
            directory.mkdir(parents=True, exist_ok=True)
            target = directory / f"{name}_R{default_return:g}.json"
            target.write_text(json.dumps(timeseries))
            entry["timeseries_file"] = str(target)
        if options.get("settlement_log", True):
            entry["settlementLog"] = (response.get("settlementLog")
                                      or (response.get("batches") or [{}])[0].get("settlementLog"))
            entry["settlementLogUnheld"] = (
                response.get("settlementLogUnheld")
                if response.get("settlementLogUnheld") is not None
                else (response.get("batches") or [{}])[0].get("settlementLogUnheld"))
    entry.update(running.memory_kb())
    return entry


def settlement_identities(entry: dict, expect_log: bool) -> list:
    """The per-settlement log must add up to the aggregate diagnostics."""
    problems = []
    missing = entry.get("missing_data") or {}
    log = entry.get("settlementLog")
    if not expect_log:
        return problems
    if log is None:
        return ["settlementLog was requested but the response carries none"]
    if entry.get("settlementLogUnheld") is None:
        problems.append("settlementLogUnheld missing from the response")
    try:
        pnl = sum(float(r["exposure"]) * float(r["return"]) for r in log)
        default_gross = sum(abs(float(r["exposure"])) for r in log
                            if r.get("source") == "default")
    except (KeyError, TypeError, ValueError) as error:
        return [f"settlementLog records are malformed: {error}"]
    if "delistingPnl" in missing and abs(pnl - float(missing["delistingPnl"])) > IDENTITY_TOLERANCE:
        problems.append(f"sum(exposure x return) {pnl:.12g} != delistingPnl "
                        f"{float(missing['delistingPnl']):.12g}")
    if ("defaultDelistingGross" in missing
            and abs(default_gross - float(missing["defaultDelistingGross"])) > IDENTITY_TOLERANCE):
        problems.append(f"sum |exposure| over default {default_gross:.12g} != "
                        f"defaultDelistingGross {float(missing['defaultDelistingGross']):.12g}")
    return problems


def counter_identity(configuration: dict) -> list:
    """eventsPriceChecks + OutOfRange + NotEvaluable must cover every matched event."""
    present = [key for key in PRICE_CHECK_COUNTERS if key in configuration]
    if not present:
        return ["/api/config exposes none of the three events price-check counters"]
    if len(present) != len(PRICE_CHECK_COUNTERS):
        return ["/api/config is missing "
                + ", ".join(key for key in PRICE_CHECK_COUNTERS if key not in configuration)]
    total = sum(int(configuration[key] or 0) for key in PRICE_CHECK_COUNTERS)
    matched = configuration.get("eventsLoaded")
    if matched is None:
        return ["/api/config has no eventsLoaded to check the counters against"]
    if total != int(matched):
        return [f"price-check counters sum to {total} but eventsLoaded is {matched} "
                f"(settlementSymbols {configuration.get('settlementSymbols')})"]
    return []


def settlement_frame(runs: list, universe: str) -> "pd.DataFrame":
    """Every settlement record from every run, one row each."""
    rows = []
    for run in runs:
        for record in run.get("settlementLog") or []:
            rows.append({"universe": universe or "config", "alpha": run["alpha"],
                         "defaultDelistingReturn": run["defaultDelistingReturn"],
                         "symbol": str(record.get("symbol")), "time": str(record.get("time"))[:10],
                         "bar": record.get("bar"), "exposure": float(record.get("exposure", 0.0)),
                         "return": float(record.get("return", 0.0)),
                         "source": record.get("source"),
                         "successor": record.get("successor"),
                         "transferred": float(record.get("transferred") or 0.0),
                         "cashShare": (float(record["cashShare"])
                                       if record.get("cashShare") is not None else np.nan),
                         "stockShare": (float(record["stockShare"])
                                        if record.get("stockShare") is not None else np.nan)})
    return pd.DataFrame(rows, columns=["universe", "alpha", "defaultDelistingReturn", "symbol",
                                       "time", "bar", "exposure", "return", "source",
                                       "successor", "transferred", "cashShare", "stockShare"])


def events_metadata(path: Path = None) -> "pd.DataFrame":
    """cacheUnitStatus and deal structure per security, plus the master ticker.

    `path` defaults to the repo events file; the harness passes the file named in the
    config's events block so the worklist/reason tables describe the file the run used.
    """
    events = pd.read_parquet(path or Path(__file__).resolve().parents[2] / "data/events/events.parquet")
    columns = ["tradingItemId"] + [c for c in EVENTS_METADATA_COLUMNS if c in events.columns]
    meta = events[columns].copy()
    meta["tradingItemId"] = meta.tradingItemId.astype(str)
    try:
        master = pd.read_parquet(MASTER_PARQUET, columns=["symbol"])
        master.index = master.index.astype(str)
        meta["ticker"] = meta.tradingItemId.map(master["symbol"])
    except Exception:
        meta["ticker"] = None
    return meta.drop_duplicates("tradingItemId").set_index("tradingItemId")


def impact_tables(frame: "pd.DataFrame", meta: "pd.DataFrame") -> tuple:
    """Which unevaluated events move the book, and by how much.

    The R=0 to R=-1 swing is carried entirely by source=default rows, so the
    signed exposure of those rows decomposes the P&L difference by reason.
    """
    if frame.empty:
        return pd.DataFrame(), pd.DataFrame(), pd.DataFrame()
    joined = frame.join(meta, on="symbol")
    joined["cacheUnitStatus"] = joined.get("cacheUnitStatus").fillna("no_events_row")
    base = joined[joined.defaultDelistingReturn == 0.0]
    by_source = (base.groupby("source")
                 .agg(settlements=("symbol", "size"), securities=("symbol", "nunique"),
                      abs_exposure=("exposure", lambda v: float(np.abs(v).sum())))
                 .reset_index().sort_values("abs_exposure", ascending=False))
    defaults = base[base.source == "default"]
    per_alpha = (defaults.groupby(["alpha", "cacheUnitStatus"])
                 .agg(abs_exposure=("exposure", lambda v: float(np.abs(v).sum())),
                      signed_exposure=("exposure", "sum"), settlements=("symbol", "size"))
                 .reset_index())
    by_reason = (per_alpha.groupby("cacheUnitStatus")
                 .agg(securities=("settlements", "max"),
                      mean_abs_exposure=("abs_exposure", "mean"),
                      max_abs_exposure=("abs_exposure", "max"),
                      min_abs_exposure=("abs_exposure", "min"),
                      mean_pnl_swing=("signed_exposure", lambda v: float(-np.mean(v))))
                 .reset_index().sort_values("mean_abs_exposure", ascending=False))
    if not defaults.empty:
        counts = defaults.groupby("cacheUnitStatus").symbol.nunique()
        by_reason["securities"] = by_reason.cacheUnitStatus.map(counts).fillna(0).astype(int)
        total = by_reason.mean_abs_exposure.sum()
        by_reason["share_pct"] = (100.0 * by_reason.mean_abs_exposure / total) if total else 0.0
    return by_source, by_reason, per_alpha


def worklist(frame: "pd.DataFrame", meta: "pd.DataFrame", universe: str) -> "pd.DataFrame":
    """Securities whose settlement fell back to the config default, worst first."""
    if frame.empty:
        return pd.DataFrame()
    joined = frame[frame.source == "default"].join(meta, on="symbol")
    if joined.empty:
        return pd.DataFrame()
    grouped = joined.groupby("symbol")
    rows = grouped.agg(max_abs_exposure=("exposure", lambda v: float(np.abs(v).max())),
                       alphas=("alpha", "nunique")).reset_index()
    first = grouped.first()
    for column in ("ticker", "endDate", "actionCode", "cacheUnitStatus", "hasStockLeg", "actionText"):
        rows[column] = rows.symbol.map(first[column]) if column in first else None
    rows["actionText"] = rows.actionText.astype(str).str.slice(0, 120)
    rows["universe"] = universe or "config"
    rows = rows.rename(columns={"symbol": "tradingItemId"})
    return rows[["tradingItemId", "ticker", "endDate", "actionCode", "cacheUnitStatus",
                 "hasStockLeg", "max_abs_exposure", "alphas", "universe", "actionText"]] \
        .sort_values("max_abs_exposure", ascending=False)


LOG_KEY = ["universe", "alpha", "defaultDelistingReturn", "symbol", "time"]
LOG_NUMERIC = ("exposure", "return", "transferred", "cashShare", "stockShare")
# Per-unit terms of the settlement. These describe the deal, not the book size, so
# a change here is a different settlement even when the weight is untouched.
LOG_STRUCTURAL_RATIOS = ("cashShare", "stockShare", "transfer_ratio")
# Every settlement record must carry all of these. A column missing from either
# log means that aspect is simply not compared, which is a failure, not a pass.
REQUIRED_LOG_FIELDS = ("symbol", "time", "exposure", "return", "source", "successor",
                       "transferred", "cashShare", "stockShare")
RATIO_TOLERANCE = 1e-6


def _identity(series: "pd.Series") -> "pd.Series":
    """Canonical text for an id column.

    An outer merge promotes an int column to float as soon as one side has a
    missing row, which would otherwise make -1 and -1.0 compare unequal.
    """
    def canonical(value):
        if value is None or (isinstance(value, float) and pd.isna(value)):
            return ""
        if isinstance(value, (int, np.integer)):
            return str(int(value))
        if isinstance(value, (float, np.floating)):
            return str(int(value)) if float(value).is_integer() else repr(float(value))
        return str(value)
    return series.map(canonical)


# A fixed book normalises to gross one, so moving one settlement date changes every
# co-held weight slightly. Exposure-only drift below this is renormalisation, not a
# regression; a changed source, return, date or presence always is.
RENORMALISATION_TOLERANCE = 1e-3


def compare_settlement_logs(before: "pd.DataFrame", after: "pd.DataFrame",
                            expected: set = None, tolerance: float = IDENTITY_TOLERANCE,
                            renormalisation: float = RENORMALISATION_TOLERANCE) -> dict:
    """Row-level diff of two settlement logs, keyed on universe/alpha/R/symbol/time.

    Securities outside `expected` must not move at all: anything that does is a
    regression, which is what gates the correction being safe to keep.
    """
    gaps = []
    for label, frame in (("before", before), ("after", after)):
        for name in REQUIRED_LOG_FIELDS:
            if name not in frame.columns:
                gaps.append(f"{label}.{name}")
    if gaps:
        empty = pd.DataFrame()
        return {"merged": empty, "changed": empty,
                "totals": pd.DataFrame(columns=LOG_KEY + ["pnl_before", "pnl_after", "pnl_diff",
                                                          "changed_rows", "added", "removed"]),
                "securities": [], "unexpected": [],
                "renormalisation_securities": [], "renormalisation_rows": 0,
                "renormalisation_max_exposure": 0.0, "renormalisation_pnl": 0.0,
                "absent_fields": sorted(gaps), "unlogged_fields": [],
                "allowlist": None if expected is None else sorted(expected),
                "status": "FAIL"}
    for frame in (before, after):
        frame["symbol"] = frame.symbol.astype(str)
        frame["time"] = frame.time.astype(str).str.slice(0, 10)
        if {"transferred", "exposure"} <= set(frame.columns):
            # Per-unit share of the book handed over: the weight cancels, so this
            # isolates a changed deal from a renormalised position.
            frame["transfer_ratio"] = np.where(frame.exposure.abs() > 0,
                                               frame.transferred / frame.exposure, np.nan)
    # One side missing a field breaks comparability; neither side having it just
    # means the field was never logged, which is reported but not a failure.
    checked = LOG_NUMERIC + ("transfer_ratio",)
    absent = [name for name in checked
              if (name in before.columns) != (name in after.columns)]
    unlogged = [name for name in checked
                if name not in before.columns and name not in after.columns]
    absent += [f"required.{name}" for name in REQUIRED_LOG_FIELDS
               if name not in before.columns or name not in after.columns]
    merged = before.merge(after, on=LOG_KEY, how="outer", suffixes=("_before", "_after"),
                          indicator=True)
    merged["pnl_before"] = merged.exposure_before * merged["return_before"]
    merged["pnl_after"] = merged.exposure_after * merged["return_after"]
    merged["pnl_diff"] = merged.pnl_after.fillna(0.0) - merged.pnl_before.fillna(0.0)
    changed = merged["_merge"] != "both"
    for name in LOG_NUMERIC:
        left, right = f"{name}_before", f"{name}_after"
        if left in merged and right in merged:
            difference = (merged[right] - merged[left]).abs()
            merged[f"{name}_diff"] = difference
            changed |= difference.fillna(0.0) > tolerance
            changed |= merged[left].isna() != merged[right].isna()
    if "source_before" in merged and "source_after" in merged:
        changed |= (merged.source_before.fillna("") != merged.source_after.fillna(""))
    # transfer_ratio rides along with the numeric fields but is judged as a ratio.
    if "transfer_ratio_before" in merged and "transfer_ratio_after" in merged:
        merged["transfer_ratio_diff"] = (merged.transfer_ratio_after
                                         - merged.transfer_ratio_before).abs()
        changed |= merged["transfer_ratio_diff"].fillna(0.0) > RATIO_TOLERANCE
        changed |= merged.transfer_ratio_before.isna() != merged.transfer_ratio_after.isna()
    if "successor_before" in merged and "successor_after" in merged:
        changed |= _identity(merged.successor_before) != _identity(merged.successor_after)
    merged["changed"] = changed
    structural = merged["_merge"] != "both"
    if "source_before" in merged and "source_after" in merged:
        structural |= merged.source_before.fillna("") != merged.source_after.fillna("")
    if "return_diff" in merged:
        structural |= merged["return_diff"].fillna(0.0) > tolerance
    if "successor_before" in merged and "successor_after" in merged:
        # A different surviving security is a different settlement.
        structural |= _identity(merged.successor_before) != _identity(merged.successor_after)
    for name in LOG_STRUCTURAL_RATIOS:
        column = f"{name}_diff"
        if column in merged:
            structural |= merged[column].fillna(0.0) > RATIO_TOLERANCE
            structural |= merged[f"{name}_before"].isna() != merged[f"{name}_after"].isna()
    merged["structural"] = changed & structural
    rows = merged[merged.changed]
    securities = set(rows.symbol.astype(str))
    allowed = set(expected) if expected is not None else set()
    # No allow-list means nothing was vetted, so every change counts as
    # unexpected: defaulting to "whatever changed is fine" would pass silently.
    outside = securities - allowed
    structural_rows = merged[merged.structural]
    unexpected = sorted(set(structural_rows.symbol.astype(str)) - allowed)
    drift_rows = rows[rows.symbol.astype(str).isin(outside) & ~rows.structural]
    drift_max = float(drift_rows.get("exposure_diff", pd.Series([0.0])).max() or 0.0)
    over_drift = sorted(set(drift_rows[drift_rows.get("exposure_diff", 0.0)
                                       > renormalisation].symbol.astype(str)))
    unexpected = sorted(set(unexpected) | set(over_drift))
    totals = (merged.groupby(["universe", "alpha", "defaultDelistingReturn"])
              .agg(pnl_before=("pnl_before", "sum"), pnl_after=("pnl_after", "sum"),
                   pnl_diff=("pnl_diff", "sum"),
                   changed_rows=("changed", "sum"),
                   added=("_merge", lambda v: int((v == "right_only").sum())),
                   removed=("_merge", lambda v: int((v == "left_only").sum())))
              .reset_index())
    return {"merged": merged, "changed": rows, "totals": totals,
            "securities": sorted(securities), "unexpected": unexpected,
            "renormalisation_securities": sorted(set(drift_rows.symbol.astype(str)) - set(over_drift)),
            "renormalisation_rows": int(len(drift_rows)),
            "renormalisation_max_exposure": drift_max,
            "renormalisation_pnl": float(drift_rows.pnl_diff.sum()) if len(drift_rows) else 0.0,
            "absent_fields": absent, "unlogged_fields": unlogged,
            "allowlist": None if expected is None else sorted(expected),
            "status": "FAIL" if (unexpected or absent) else "PASS"}


def run_pnl_table(before_dirs: list, after_dirs: list) -> "pd.DataFrame":
    """Whole-run P&L and Sharpe, paired on universe/alpha/defaultDelistingReturn.

    The settlement-day differences only cover the settlement bars; this is the
    strategy P&L including every holding bar, which is what actually moves.
    """
    def collect(directories, label):
        rows = []
        for directory in directories:
            path = Path(directory) / "report.json"
            if not path.exists():
                raise FileNotFoundError(f"no report.json in {directory}")
            report = json.loads(path.read_text())
            universe = report.get("universe") or "config"
            for run in report["runs"]:
                if run.get("status") != "OK":
                    continue
                rows.append({"universe": universe, "alpha": run["alpha"],
                             "defaultDelistingReturn": run["defaultDelistingReturn"],
                             f"pnl_{label}": run.get("pnl"),
                             f"sharpe_{label}": run.get("sharpe_full"),
                             f"mdd_{label}": run.get("max_drawdown"),
                             f"turnover_{label}": run.get("turnover_total")})
        return pd.DataFrame(rows)

    before = collect(before_dirs, "before")
    after = collect(after_dirs, "after")
    table = before.merge(after, on=["universe", "alpha", "defaultDelistingReturn"], how="outer")
    table["pnl_diff"] = table.pnl_after - table.pnl_before
    table["sharpe_diff"] = table.sharpe_after - table.sharpe_before
    table["turnover_diff"] = table.turnover_after - table.turnover_before
    return table.sort_values(["universe", "alpha", "defaultDelistingReturn"])


def render_run_pnl(table: "pd.DataFrame") -> list:
    lines = ["", "## 전체 PnL 변화 (보유손익 포함, 하네스 run 단위)", "",
             "| 유니버스 | alpha | R | PnL 전 | 후 | 차이 | Sharpe 전 | 후 | 차이 | turnover 차 |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for row in table.to_dict("records"):
        def number(key, digits=4):
            value = row.get(key)
            return "-" if value is None or pd.isna(value) else f"{value:+.{digits}f}"
        lines.append(
            f"| {row['universe']} | {row['alpha']} | {row['defaultDelistingReturn']:g} "
            f"| {number('pnl_before')} | {number('pnl_after')} | {number('pnl_diff')} "
            f"| {number('sharpe_before', 3)} | {number('sharpe_after', 3)} "
            f"| {number('sharpe_diff', 3)} | {number('turnover_diff', 4)} |")
    return lines


